import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(import.meta.dirname, "..");
const output = resolve(root, "packages/vue3/src/prop-values.ts");

function ordered(values) {
  // TS interns unions, so its iteration order can change with unrelated imports.
  // Keep familiar size order without treating this ordering hint as a source of allowed values.
  const sizes = ["none", "xs", "sm", "md", "lg", "xl", "full"];
  if (values.every(value => sizes.includes(value))) return values.sort((a, b) => sizes.indexOf(a) - sizes.indexOf(b));
  return values.sort((a, b) => typeof a === "number" && typeof b === "number" ? a - b :
    (typeof a + ":" + a).localeCompare(typeof b + ":" + b, "en"));
}

/** Finite component-owned choices only: open strings/numbers, objects, events and Boolean-only props are excluded. */
export function collectPropValues() {
  const config = ts.getParsedCommandLineOfConfigFile(resolve(root, "packages/vue3/tsconfig.json"), {}, {
    ...ts.sys, onUnRecoverableConfigFileDiagnostic: diagnostic => { throw Error(ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")); },
  });
  // Read workspace types even before the first package build (or after token types change).
  const program = ts.createProgram(config.fileNames, { ...config.options, noEmit: true,
    paths: { ...config.options.paths, "@kjun-ui/tokens": [resolve(root, "packages/tokens/src/index.ts")] },
  });
  const checker = program.getTypeChecker(), entry = program.getSourceFile(resolve(root, "packages/vue3/src/components.ts"));
  const result = {};
  for (const exported of checker.getExportsOfModule(checker.getSymbolAtLocation(entry)).sort((a, b) => a.name.localeCompare(b.name))) {
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const component = checker.getTypeOfSymbolAtLocation(symbol, symbol.valueDeclaration || entry);
    const instance = component.getConstructSignatures()[0]?.getReturnType();
    const member = instance?.getProperty("$props");
    if (!member) throw Error("Cannot inspect public component props: " + exported.name);
    const props = checker.getTypeOfSymbolAtLocation(member, entry), values = {};
    for (const prop of checker.getPropertiesOfType(props).sort((a, b) => a.name.localeCompare(b.name))) {
      // Vue's inherited VNode attributes and listeners are not KJUN's prop contract.
      if (!prop.declarations?.some(node => node.getSourceFile().fileName.startsWith(resolve(root, "packages/vue3/src") + "/"))) continue;
      const type = checker.getTypeOfSymbolAtLocation(prop, entry);
      const parts = (type.isUnion() ? type.types : [type]).filter(part => !(part.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null)));
      if (!parts.length || !parts.every(part => part.flags & (ts.TypeFlags.StringLiteral | ts.TypeFlags.NumberLiteral | ts.TypeFlags.BooleanLiteral))) continue;
      if (!parts.some(part => part.flags & (ts.TypeFlags.StringLiteral | ts.TypeFlags.NumberLiteral))) continue;
      values[prop.name] = ordered(parts.map(part => part.flags & ts.TypeFlags.BooleanLiteral ? part.intrinsicName === "true" : part.value));
    }
    if (Object.keys(values).length) result[exported.name] = values;
  }
  if (!result.KjunButton?.size || !result.KjunInput?.size) throw Error("Could not resolve component prop choices");
  return result;
}

export function propValuesSource(values) {
  const rows = Object.entries(values).map(([name, props]) => `  ${name}: Object.freeze({\n${Object.entries(props)
    .map(([prop, choices]) => `    ${prop}: Object.freeze(${JSON.stringify(choices)} as const),`).join("\n")}\n  }),`);
  return `// Generated by scripts/prop-values.mjs from the public Vue component types. Do not edit.\n` +
    `/** Finite prop choices. Omission/nullability follows each prop type; open-ended and Boolean-only props are not listed. */\n` +
    `export const kjunPropValues = Object.freeze({\n${rows.join("\n")}\n});\n`;
}

export async function generatePropValues(check = false) {
  const values = collectPropValues(), source = propValuesSource(values);
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== source) {
    if (check) throw Error("Prop choices are stale; run npm run props:generate in kjun_ui_dev.");
    await writeFile(output, source);
  }
  console.log(`Vue prop choices ${check ? "checked" : "generated"}: ${Object.keys(values).length} components.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generatePropValues(process.argv.includes("--check"));
