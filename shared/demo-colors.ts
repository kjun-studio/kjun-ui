export const demoFont = "Inter, Pretendard, system-ui, sans-serif";
export const cssColorName = (role: string) =>
  "--kjun-" + role.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
export function applyDemoColors(palette: PaletteName) {
  document.documentElement.style.colorScheme = palette === "dark" ? "dark" : "light";
  for (const [role, value] of Object.entries({
    ...demoPalettes[palette],
    ...demoDomainPalettes[palette],
  }))
    document.documentElement.style.setProperty(cssColorName(role), value);
  document.documentElement.style.setProperty("--kjun-font", demoFont);
}
